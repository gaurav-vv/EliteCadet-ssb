#!/bin/bash
# Builds supabase/catchup/production_catchup_0005_<last>.sql: every migration from
# 0005 up to the newest one in supabase/migrations, in order, wrapped in ONE
# transaction with pre-checks, for a database that is at 0004 (a hosted project
# that has only had 0001–0004 applied). Paste the output into the Supabase SQL
# Editor once; any error rolls the whole thing back.
#
# Re-run this script after adding or editing a migration. It deletes older
# production_catchup_*.sql files so only one current file exists.
# Check what the hosted database really has BEFORE using it (docs/RUNNING_GUIDE.md).
set -euo pipefail
cd "$(dirname "$0")/../.."

files=()
for f in supabase/migrations/*.sql; do
  n=$(basename "$f" | cut -c1-4)
  [[ "$n" < "0005" ]] && continue
  files+=("$f")
done
first=$(basename "${files[0]}" | cut -c1-4)
last=$(basename "${files[${#files[@]}-1]}" | cut -c1-4)
OUT="supabase/catchup/production_catchup_${first}_${last}.sql"
rm -f supabase/catchup/production_catchup_*.sql

{
  cat <<SQL
-- GENERATED by supabase/catchup/build.sh from supabase/migrations/${first}–${last}.
-- Do not edit by hand. For a database where 0001–0004 are applied and 0005 is
-- not. All-or-nothing: any error rolls everything back.
begin;

SQL
  cat <<'SQL'
do $$
begin
  if to_regclass('public.profiles') is null or to_regclass('public.batches') is null then
    raise exception 'catch-up: 0001–0003 are not applied (profiles/batches missing).';
  end if;
  if not exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid
                 where t.typname = 'user_role' and e.enumlabel = 'super_admin') then
    raise exception 'catch-up: run 0004_super_admin_role.sql on its own first.';
  end if;
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'profiles' and column_name = 'status') then
    raise exception 'catch-up: 0005 is already applied; apply the remaining migrations individually.';
  end if;
end;
$$;
SQL
  for f in "${files[@]}"; do
    printf '\n-- ===========================================================================\n-- %s\n-- ===========================================================================\n' "$(basename "$f")"
    cat "$f"
  done
  printf "\nnotify pgrst, 'reload schema';\n\ncommit;\n"
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
